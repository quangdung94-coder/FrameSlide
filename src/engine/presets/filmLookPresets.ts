import { DEFAULT_SUPER8_PARAMS, type FilmLookId, type FilmLookParams } from '@shared/types';

export interface FilmLookPresetMeta {
  id: FilmLookId;
  name: string;
  desc: string;
  params: FilmLookParams;
}

function makeLook(id: FilmLookId, overrides: Partial<FilmLookParams>): FilmLookParams {
  return {
    ...DEFAULT_SUPER8_PARAMS,
    presetId: id,
    enabled: id !== 'clean',
    ...overrides,
  };
}

